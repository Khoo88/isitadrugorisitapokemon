import { readFileSync, writeFileSync } from "fs";

const existing = JSON.parse(
  readFileSync(new URL("../src/data/items.json", import.meta.url), "utf8"),
);
const names = new Set(existing.map((i) => i.name.toLowerCase()));

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function tryAdd(items, entry) {
  const key = entry.name.toLowerCase();
  if (names.has(key)) return false;
  if (entry.name.length > 14) return false;
  if (/\s/.test(entry.name)) return false;
  names.add(key);
  items.push(entry);
  return true;
}

