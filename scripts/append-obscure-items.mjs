const appended = [];
let drugId = 151;
let pokeId = 151;

for (const [name, trait] of drugCandidates) {
  if (appended.filter((i) => i.category === "drug").length >= 50) break;
  if (
    tryAdd(appended, {
      id: `drug-${drugId}`,
      name,
      category: "drug",
      slug: slugify(name),
      quizTrait: trait,
      description: trait,
    })
  ) {
    drugId++;
  }
}

for (const [name, trait] of pokemonCandidates) {
  if (appended.filter((i) => i.category === "pokemon").length >= 50) break;
  if (
    tryAdd(appended, {
      id: `pokemon-${pokeId}`,
      name,
      category: "pokemon",
      slug: slugify(name),
      quizTrait: trait,
      description: trait,
    })
  ) {
    pokeId++;
  }
}

const drugCount = appended.filter((i) => i.category === "drug").length;
const pokeCount = appended.filter((i) => i.category === "pokemon").length;
if (drugCount !== 50 || pokeCount !== 50) {
  throw new Error(`Expected 50+50, got ${drugCount}+${pokeCount}`);
}

const merged = [...existing, ...appended];
writeFileSync(
  new URL("../src/data/items.json", import.meta.url),
  JSON.stringify(merged, null, 2) + "\n",
);
console.log(`Appended ${appended.length}. Total: ${merged.length}`);
