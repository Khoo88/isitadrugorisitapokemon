function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function tryAdd(items, entry) {
  const key = entry.name.toLowerCase();
  if (names.has(key)) return false;
  if (/\s|-/.test(entry.name)) return false;
  names.add(key);
  items.push(entry);
  return true;
}

